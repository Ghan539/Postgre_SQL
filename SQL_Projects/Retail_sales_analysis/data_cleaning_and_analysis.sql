-- data analysis
-- Write a SQL query to retrieve all columns for sales made on 2022-11-05.
select * from retail_sales
where sale_date = ' 2022-11-05';

-- Write a SQL query to retrieve all transactions where the category is Clothing and the quantity sold is more than 4.
select * from retail_sales 
where category = 'Clothing' and quantity > 4;


-- Write a SQL query to calculate the total sales (total_sale) for each category.
select 
	Category ,
	sum(total_sale) as total_sales
from retail_sales
group by Category
;


-- Write a SQL query to find the average age of customers who purchased items from the Beauty category.
select
	avg(age) as avg_age
from retail_sales
where Category = 'Beauty'
group by Category;

-- Write a SQL query to find all transactions where total_sale is greater than 1000.
select 
	*
from retail_sales	
where total_sale > 1000;

-- Write a SQL query to find the total number of transactions made by each gender.
select
	gender,
	count(*) as total_transactions
from retail_sales
group by gender;


-- Write a SQL query to calculate the average sale for each gender.
select 
	gender,
	round(avg(total_sale)::numeric,2)  as avg_sale
from retail_sales
group by gender ;

-- Find all transactions where the category is Beauty and the gender is Female.
select * from retail_sales
where Category ='Beauty' and gender = 'Female';


-- Write a SQL query to find the number of transactions for each category.
select
	Category,
	count(*) as no_of_transactions
from retail_sales
group by Category;

-- Write a SQL query to find the total revenue generated by each category for female customers.
select
	Category,
	sum(total_sale) as total_revenue
from retail_sales
where gender ='Female'
group by Category;

